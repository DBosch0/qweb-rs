#!/usr/bin/env bash
# Build the qweb-wasm package.
#   scripts/build_wasm.sh               -> target/wasm-pkg/{no-modules,nodejs}
#   scripts/build_wasm.sh <web addon>   -> also writes <web addon>/static/src/core/qweb_wasm/
# Needs the wasm32-unknown-unknown target and wasm-bindgen 0.2.130 on PATH.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
cargo build -q -p qweb-wasm --target wasm32-unknown-unknown --profile wasm
WASM=target/wasm32-unknown-unknown/wasm/qweb_wasm.wasm
for t in no-modules nodejs; do
    # Drop the function names (about 33 KB gzipped) and the producers section.
    wasm-bindgen --target "$t" --remove-name-section --remove-producers-section \
        --out-dir "target/wasm-pkg/$t" "$WASM"
done
if [ $# -ge 1 ]; then
    OUT="$1/static/src/core/qweb_wasm"
    mkdir -p "$OUT"
    {
        echo "// Generated by qweb-rs scripts/build_wasm.sh from the wasm-bindgen 'no-modules' glue. Do not edit."
        echo "/* eslint-disable */"
        echo 'import { WASM_BASE64 } from "./qweb_wasm_bytes";'
        echo
        sed -e 's/^let wasm_bindgen = /const wasm_bindgen = /' target/wasm-pkg/no-modules/qweb_wasm.js
        cat <<'JS'

let initialized = false;

/**
 * Instantiate the module (synchronously, on first use) and return its exports:
 * `TemplateStore`, `Renderer` and `applyInheritanceServer`.
 */
export function getQwebWasm() {
    if (!initialized) {
        const bytes = Uint8Array.fromBase64
            ? Uint8Array.fromBase64(WASM_BASE64)
            : Uint8Array.from(atob(WASM_BASE64), (c) => c.charCodeAt(0));
        wasm_bindgen.initSync({ module: bytes });
        initialized = true;
    }
    return wasm_bindgen;
}
JS
    } > "$OUT/qweb_wasm.js"
    {
        echo "// Generated by qweb-rs scripts/build_wasm.sh: qweb_wasm_bg.wasm in base64. Do not edit."
        printf 'export const WASM_BASE64 =\n    "%s";\n' "$(base64 < target/wasm-pkg/no-modules/qweb_wasm_bg.wasm | tr -d '\n')"
    } > "$OUT/qweb_wasm_bytes.js"
    echo "wrote $OUT"
fi
