//! # qweb-core
//!
//! A fast, host-agnostic implementation of Odoo's `QWeb` templating engine with
//! output byte-identical to the Python implementation (`ir.qweb`).
//!
//! ## Architecture
//!
//! ```text
//!  XML source ──xml::Document::parse──▶ tree ──compile::Compiler──▶ ir::Program
//!                                                                      │
//!        values (Host::Scope) + context (Host::Context) ──▶ Engine::render ──▶ String
//! ```
//!
//! * [`xml`] parses a template into an lxml-like tree (`text`/`tail`,
//!   namespaces in lxml notation).
//! * [`compile`] is a structural port of `IrQweb._compile_*`: same walk, same
//!   directive order, same static-text buffering, so whitespace and output
//!   match exactly. It produces an [`ir::Program`], whose statements mirror
//!   the Python code generated by Odoo.
//! * [`expr`] parses the Python expression subset used in templates. The
//!   compiler lowers it into [`ir::Ex`]; anything the parser does not
//!   support (lambdas, comprehensions, f-strings, ...) is handed to the host
//!   ([`Host::compile_opaque`]).
//! * [`Engine`] caches compiled programs and interprets them. Lazy content
//!   (`t-set` / `t-call` bodies) is a [`Lazy`].
//!
//! ## Hosts
//!
//! The engine never inspects values: everything value-related (attribute
//! access, operators, `str()`, truthiness, scopes, template loading) goes
//! through the [`Host`] trait, and the interpreter is monomorphised over it.
//! The Python binding (`qweb-python`) implements it on top of the `CPython`
//! object protocol, which gives exact Python semantics; `qweb-value` provides
//! a pure-Rust host used for tests, benchmarks and WASM.
//!
//! A host also provides the ORM-dependent parts (`groups`, `t-field`,
//! widgets, `t-call-assets`) and, optionally, extension hooks: custom
//! directives, attribute pre/post-processing and expression checks (see
//! [`host::CompileHooks`] and [`compile::CompileApi`]).
//!
//! ## Rendering
//!
//! With a host `MyHost`, rendering looks like this:
//!
//! ```text
//! let engine = Engine::new(MyHost::default());
//! let html = engine.render(&TemplateRef::parse("web.layout"), scope, ctx)?;
//! ```
//!
//! [`Engine::render`] loads templates through [`Host::load`], which returns
//! either an XML source (compiled and cached by the engine) or a program the
//! host compiled and cached itself ([`Engine::compile_program`]).
//!
//! ## Errors
//!
//! Errors carry a kind that hosts map onto the Python exception classes
//! (`SyntaxError`, `KeyError`, ...), and the location of the failing element
//! with the template call stack. See [`Error`].
//!
//! ## Portability
//!
//! The crate is pure Rust with `memchr` as its only dependency, and builds
//! for `wasm32-unknown-unknown`.

